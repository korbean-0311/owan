-- Supabase → SQL Editor 에 붙여넣고 RUN. (멱등 — 다시 실행해도 안전)
--
-- 시즌 시작 전(아직 아무도 레버리지 미사용)에 실행한다는 전제로,
-- 기존 멤버의 남은 레버리지를 일괄 3으로 올림.
-- (이미 일부 사용한 멤버가 있다면 이 일괄 UPDATE는 원치 않을 수 있으니 주의 —
--  현재는 시즌 시작 전이라 전원 미사용 상태)
-- ════════════════════════════════════════════════════════

-- 기본값(신규 가입자용)
alter table public.memberships alter column leverage_left set default 3;

-- 기존 멤버 일괄 3회로 (시즌 시작 전 전원 미사용 가정)
update public.memberships set leverage_left = 3;
